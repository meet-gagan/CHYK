export async function syncDatabaseMedia() {
  console.log('[Sync] Starting Media Library database cleanup and synchronization...');

  // 1. Purge all dummy / base64 / test entries that don't match our real website assets
  const deleteResult = await Media.deleteMany({
    $or: [
      { url: { $regex: '^data:image' } },
      { title: { $regex: 'Virtual Reality Stall|Test Banner|Placeholder' } },
      { publicId: { $regex: '^test_' } },
    ],
  });
  console.log(`[Sync] Removed ${deleteResult.deletedCount} dummy/base64 media records.`);

  // 2. Synchronize Chinmaya Mission main website images
  let cmInserted = 0;
  let cmUpdated = 0;
  for (const item of CHINMAYA_MISSION_MEDIA) {
    const existing = await Media.findOne({
      $or: [
        { publicId: item.publicId },
        { url: item.url, page: 'Chinmaya Mission' },
        { title: item.title, page: 'Chinmaya Mission' },
      ],
    });

    if (existing) {
      await Media.findByIdAndUpdate(existing._id, {
        ...item,
        status: 'ACTIVE',
      });
      cmUpdated++;
    } else {
      await Media.create(item);
      cmInserted++;
    }
  }
  console.log(`[Sync] Chinmaya Mission Media: ${cmInserted} inserted, ${cmUpdated} updated.`);

  // 3. Synchronize Marathon website images
  let marInserted = 0;
  let marUpdated = 0;
  for (const item of MARATHON_MEDIA) {
    const existing = await Media.findOne({
      $or: [
        { publicId: item.publicId },
        { url: item.url, page: 'Marathon' },
        { title: item.title, page: 'Marathon' },
      ],
    });

    if (existing) {
      await Media.findByIdAndUpdate(existing._id, {
        ...item,
        status: 'ACTIVE',
      });
      marUpdated++;
    } else {
      await Media.create(item);
      marInserted++;
    }
  }
  console.log(`[Sync] Marathon Media: ${marInserted} inserted, ${marUpdated} updated.`);

  // 4. Clean up any remaining legacy entries in HomePage CMS pointing to older hero banner
  try {
    const homePage = await HomePage.findOne();
    if (homePage && homePage.sections) {
      let modified = false;
      homePage.sections = homePage.sections.map((sec) => {
        if (sec.type === 'hero') {
          if (!sec.imageUrl || sec.imageUrl.includes('unsplash.com') || sec.imageUrl.includes('hero_main_horiz')) {
            sec.imageUrl = '/assets/images/hero-runners-graphic.png';
            modified = true;
          }
        }
        return sec;
      });
      if (modified) {
        await homePage.save();
        console.log('[Sync] HomePage CMS hero section updated to /assets/images/hero-runners-graphic.png');
      }
    }
  } catch (err) {
    console.error('[Sync] Error updating HomePage CMS:', err.message);
  }

  const finalTotal = await Media.countDocuments();
  console.log(`[Sync] Complete! Total active media assets now in database: ${finalTotal}`);
}

// Auto-run if executed directly
if (process.argv[1] && process.argv[1].endsWith('syncWebsiteMedia.js')) {
  mongoose
    .connect(process.env.MONGODB_URI)
    .then(async () => {
      await syncDatabaseMedia();
      await mongoose.disconnect();
      process.exit(0);
    })
    .catch((err) => {
      console.error('[Sync Error]:', err);
      process.exit(1);
    });
}
